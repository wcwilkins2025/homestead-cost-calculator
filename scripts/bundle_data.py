"""Bundle data/*.json into data/bundle.js so index.html works from a plain file:// open too.
Run after editing any JSON: python scripts/bundle_data.py
The JSON files stay the source of truth; tests/run_tests.js checks the bundle matches them."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
data = {}
for key, fn in [("costs", "costs.json"), ("land", "land_values.json"), ("tax", "property_tax.json"), ("counties", "counties.json")]:
    with open(os.path.join(root, "data", fn), encoding="utf-8") as f:
        data[key] = json.load(f)
js = "/* Generated by scripts/bundle_data.py from data/*.json. Do not edit by hand. */\nwindow.HC = " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n"
with open(os.path.join(root, "data", "bundle.js"), "w", encoding="utf-8") as f:
    f.write(js)
print("bundle.js", len(js), "bytes")
